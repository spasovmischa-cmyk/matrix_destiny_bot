def get_personalized_greeting(name: str, user_id: int) -> str:
    """Получает персональное приветствие"""
    import hashlib
    # Используем hash user_id для выбора уникального приветствия
    index = int(hashlib.md5(str(user_id).encode()).hexdigest(), 16) % len(GREETINGS)
    return GREETINGS[index].format(name=name)

